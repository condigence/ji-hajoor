package com.homefix.admin.config;

import java.time.Clock;

import org.springframework.boot.autoconfigure.condition.ConditionalOnMissingBean;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Provides a system UTC {@link Clock} bean so time-dependent components (Audit_Log timestamps,
 * dashboard snapshot times) can be made deterministic under test by injecting a fixed clock.
 */
@Configuration
public class ClockConfig {

    @Bean
    @ConditionalOnMissingBean
    public Clock clock() {
        return Clock.systemUTC();
    }
}
